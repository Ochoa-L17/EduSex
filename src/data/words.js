// Generador infinito que selecciona palabras asegurando variedad y nunca quedarse sin retos
export const getRandomWord = (excludedIds = []) => {
  const available = WORD_BANK.filter((w) => !excludedIds.includes(w.id));
  if (available.length === 0) {
    // Si ya jugó todas, reiniciamos el ciclo conservando la última para no repetir
    const lastId = excludedIds[excludedIds.length - 1];
    const pool = WORD_BANK.filter((w) => w.id !== lastId);
    return pool[Math.floor(Math.random() * pool.length)];
  }
  return available[Math.floor(Math.random() * available.length)];
};
